create policy "Orders insert" on public.orders for insert with check (auth.uid() = buyer_id);
create policy "Promotions read" on public.promotions for select using (true);
create policy "Promotions manage" on public.promotions for all using (auth.uid() = creator_id) with check (auth.uid() = creator_id);
create policy "Reviews read" on public.reviews for select using (true);
create policy "Reviews insert" on public.reviews for insert with check (auth.uid() = buyer_id);
create policy "Wishlists manage" on public.wishlists for all using (auth.uid() = buyer_id) with check (auth.uid() = buyer_id);
create policy "Coupons read" on public.coupons for select using (true);
