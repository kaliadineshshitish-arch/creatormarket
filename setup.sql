-- Extensions -----------------------------------------------------------------
create extension if not exists pgcrypto;

-- Products -------------------------------------------------------------------
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  creator_id uuid references auth.users(id) on delete cascade,
  category text,
  title text not null,
  description text,
  price numeric(10,2) not null default 0,
  product_url text,
  image_url text,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);
-- Make sure the columns the app expects exist even on an older table.
alter table public.products add column if not exists category text;
alter table public.products add column if not exists product_url text;
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists is_published boolean not null default true;
alter table public.products add column if not exists created_at timestamptz not null default now();

-- Orders ---------------------------------------------------------------------
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  kind text not null default 'product',       -- product | plan | promotion
  product_id uuid,                            -- references public.products(id)
  plan text,
  promo_days integer,
  amount numeric(10,2) not null default 0,
  currency text not null default 'INR',
  status text not null default 'pending',     -- pending | paid | failed
  cf_order_id text,
  payment_id text,
  created_at timestamptz not null default now()
);
alter table public.orders add column if not exists kind text not null default 'product';
alter table public.orders add column if not exists plan text;
alter table public.orders add column if not exists promo_days integer;
alter table public.orders add column if not exists currency text not null default 'INR';
alter table public.orders add column if not exists cf_order_id text;

-- Promotions -----------------------------------------------------------------
create table if not exists public.promotions (
  id bigint generated by default as identity primary key,
  creator_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  plan_days integer not null check (plan_days in (1,3,7)),
  amount numeric(10,2) not null default 0,
  status text not null default 'active' check (status in ('active','expired','cancelled')),
  expires_at timestamptz not null,
  created_at timestamptz default now()
);

-- Reviews --------------------------------------------------------------------
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products(id) on delete cascade,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text not null,
  created_at timestamptz default now(),
  unique(product_id, buyer_id)
);

-- Wishlists ------------------------------------------------------------------
create table if not exists public.wishlists (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  created_at timestamptz default now(),
  unique(buyer_id, product_id)
);

-- Coupons --------------------------------------------------------------------
create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_percent numeric(5,2) not null check (discount_percent > 0 and discount_percent <= 100),
  active boolean not null default true,
  expires_at timestamptz,
  created_at timestamptz default now()
);

-- Notifications --------------------------------------------------------------
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz default now()
);

-- Row Level Security ---------------------------------------------------------
alter table public.products      enable row level security;
alter table public.orders        enable row level security;
alter table public.promotions    enable row level security;
alter table public.reviews       enable row level security;
alter table public.wishlists     enable row level security;
alter table public.coupons       enable row level security;
alter table public.notifications enable row level security;

-- Products: public read for published items; creators manage their own.
drop policy if exists "Anyone can view published products" on public.products;
drop policy if exists "Creators insert own products" on public.products;
drop policy if exists "Creators update own products" on public.products;
drop policy if exists "Creators delete own products" on public.products;
create policy "Anyone can view published products" on public.products for select using (is_published = true or auth.uid() = creator_id);
create policy "Creators insert own products" on public.products for insert with check (auth.uid() = creator_id);
create policy "Creators update own products" on public.products for update using (auth.uid() = creator_id) with check (auth.uid() = creator_id);
create policy "Creators delete own products" on public.products for delete using (auth.uid() = creator_id);

-- Orders: buyers see/create their own. Status changes happen server-side only
-- (the service role bypasses RLS), so no client UPDATE policy is granted.
drop policy if exists "Buyers can view their orders" on public.orders;
drop policy if exists "Buyers can create their orders" on public.orders;
create policy "Buyers can view their orders" on public.orders for select using (auth.uid() = buyer_id);
create policy "Buyers can create their orders" on public.orders for insert with check (auth.uid() = buyer_id);

-- Promotions.
drop policy if exists "Anyone can view active promotions" on public.promotions;
drop policy if exists "Creators manage own promotions" on public.promotions;
create policy "Anyone can view active promotions" on public.promotions for select using (status = 'active' and expires_at > now());
create policy "Creators manage own promotions" on public.promotions for all using (auth.uid() = creator_id) with check (auth.uid() = creator_id);

-- Reviews.
drop policy if exists "Anyone can read reviews" on public.reviews;
drop policy if exists "Buyers create own reviews" on public.reviews;
drop policy if exists "Buyers update own reviews" on public.reviews;
create policy "Anyone can read reviews" on public.reviews for select using (true);
create policy "Buyers create own reviews" on public.reviews for insert with check (auth.uid() = buyer_id);
create policy "Buyers update own reviews" on public.reviews for update using (auth.uid() = buyer_id) with check (auth.uid() = buyer_id);

-- Wishlists.
drop policy if exists "Buyers manage own wishlist" on public.wishlists;
create policy "Buyers manage own wishlist" on public.wishlists for all using (auth.uid() = buyer_id) with check (auth.uid() = buyer_id);

-- Coupons.
drop policy if exists "Anyone can read active coupons" on public.coupons;
create policy "Anyone can read active coupons" on public.coupons for select using (active = true and (expires_at is null or expires_at > now()));

-- Notifications.
drop policy if exists "Users manage own notifications" on public.notifications;
create policy "Users manage own notifications" on public.notifications for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Indexes --------------------------------------------------------------------
create index if not exists idx_products_creator_id on public.products(creator_id);
create index if not exists idx_products_published_created on public.products(is_published, created_at desc);
create index if not exists idx_orders_buyer_created on public.orders(buyer_id, created_at desc);
create index if not exists idx_orders_cf_order_id on public.orders(cf_order_id);
create index if not exists idx_promotions_product_expiry on public.promotions(product_id, expires_at);
create index if not exists idx_reviews_product on public.reviews(product_id);
create index if not exists idx_notifications_user_read on public.notifications(user_id, is_read);


